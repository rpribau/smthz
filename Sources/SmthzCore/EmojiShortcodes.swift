import Foundation

/// Emoji → shortcode lookup used for worktree names and `:shortcode:` suggestions
/// (M4-D5 a: the emojibase dataset Orca uses, embedded as source below).
public enum EmojiShortcodes {
    public struct Entry: Equatable, Sendable {
        public var emoji: String
        public var shortcode: String
    }

    private struct Catalog: Sendable {
        var entries: [Entry]
        var primaryByEmoji: [String: String]
    }

    /// Built on first use (about 2,600 shortcodes).
    private static let catalog: Catalog = {
        var entries: [Entry] = []
        var primary: [String: String] = [:]
        for line in rawDataset.split(separator: "\n") {
            let parts = line.split(separator: " ", maxSplits: 1)
            guard parts.count == 2 else { continue }
            let scalars = parts[0].split(separator: "-").compactMap { UInt32($0, radix: 16).flatMap(Unicode.Scalar.init) }
            var emoji = ""
            emoji.unicodeScalars.append(contentsOf: scalars)
            let codes = parts[1].split(separator: ",").map(String.init)
            entries += codes.map { Entry(emoji: emoji, shortcode: $0) }
            primary[lookupKey(emoji)] = primaryShortcode(codes)
        }
        return Catalog(entries: entries, primaryByEmoji: primary)
    }()

    /// Every (emoji, shortcode) pair, skin-tone aliases excluded.
    public static var entries: [Entry] { catalog.entries }

    /// Branch-friendly shortcode for one emoji (variation selectors and skin tones ignored).
    public static func shortcode(for emoji: String) -> String? {
        catalog.primaryByEmoji[lookupKey(emoji)]
    }

    /// Replaces each known emoji grapheme with ` shortcode ` (underscores become hyphens),
    /// like Orca's `replaceKnownEmojiWithShortcodes`.
    public static func replaceKnownEmoji(in input: String) -> String {
        var output = ""
        for character in input {
            if let code = shortcode(for: String(character)) {
                output += " \(code.replacingOccurrences(of: "_", with: "-")) "
            } else {
                output.append(character)
            }
        }
        return output
    }

    /// Prefer a spelled-out alias: skip `+1`, short stubs (`no`, `v`) and `flag_` names.
    static func primaryShortcode(_ codes: [String]) -> String {
        let named = codes.filter { $0.first?.isLetter == true && $0.first?.isASCII == true }
        return named.first { $0.count >= 3 && !$0.hasPrefix("flag_") }
            ?? named.first { $0.count >= 3 }
            ?? named.first
            ?? codes[0]
    }

    static func lookupKey(_ emoji: String) -> String {
        var key = ""
        key.unicodeScalars.append(contentsOf: emoji.unicodeScalars.filter {
            $0.value != 0xFE0F && !(0x1F3FB...0x1F3FF).contains($0.value)
        })
        return key
    }
}


#!/usr/bin/env python3
"""Generate CHAT1's used wire subset; schema generation never starts a model turn."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

# Keep only the fields the client consumes. Unknown optional schema fields are ignored by Codable.
FIELDS = {
    'ClientInfo': ['name', 'version'],
    'InitializeParams': ['clientInfo'],
    'InitializeResponse': ['userAgent'],
    'ThreadStartParams': ['cwd', 'model', 'approvalPolicy', 'sandbox'],
    'ThreadResumeParams': ['threadId', 'approvalPolicy', 'sandbox'],
    'ThreadStartResponse': ['thread'],
    'Thread': ['id'],
    'TurnStartParams': ['threadId', 'input'],
    'TextInput': ['type', 'text'],
    'TurnStartResponse': ['turn'],
    'Turn': ['id'],
    'CommandExecutionRequestApprovalResponse': ['decision'],
    'PermissionsRequestApprovalParams': ['threadId', 'turnId', 'itemId', 'cwd', 'reason', 'permissions'],
    'PermissionsRequestApprovalResponse': ['permissions', 'scope'],
    'TurnInterruptParams': ['threadId', 'turnId'],
    'AgentMessageDeltaNotification': ['threadId', 'turnId', 'itemId', 'delta'],
    'CommandExecutionRequestApprovalParams': ['threadId', 'turnId', 'itemId', 'command', 'cwd', 'reason'],
    'FileChangeRequestApprovalParams': ['threadId', 'turnId', 'itemId', 'reason', 'grantRoot'],
}

def generate(root, output):
    schemas = [json.loads(path.read_text()) for path in root.rglob('*.json')]
    def schema_for(name):
        if name == 'TextInput':
            union = schema_for('UserInput')
            return next(item for item in union['oneOf'] if item.get('title') == 'TextUserInput')
        for schema in schemas:
            if schema.get('title') == name:
                return schema
            if name in schema.get('definitions', {}):
                return schema['definitions'][name]
        raise ValueError(f'Missing schema: {name}')

    def swift_type(prop):
        kind = prop.get('type')
        if kind == 'string' or kind == ['string', 'null']:
            return 'String'
        if kind == 'array':
            return '[' + swift_type(prop['items']) + ']'
        ref = prop.get('$ref')
        if ref:
            name = ref.split('/')[-1]
            if name in ('RequestPermissionProfile', 'GrantedPermissionProfile'):
                return '[String: HostJSON]'
            if name in ('AskForApproval', 'SandboxMode', 'CommandExecutionApprovalDecision', 'PermissionGrantScope'):
                return 'String'  # Only the string variants used by CHAT1.
            if name in ('AbsolutePathBuf', 'LegacyAppPathString'):
                return 'String'
            return 'Codex' + ('TextInput' if name == 'UserInput' else name)
        if 'anyOf' in prop:
            return swift_type(next(item for item in prop['anyOf'] if item.get('type') != 'null'))
        if 'allOf' in prop:
            return swift_type(prop['allOf'][0])
        raise ValueError(f'Review changed schema: {prop}')

    lines = ['// Generated by scripts/generate-codex-protocol.py from codex-cli 0.164.0.',
             '// App-server v2 wire subset. Regenerate and verify before widening the version gate.',
             'import Foundation', '']
    for name, fields in FIELDS.items():
        schema = schema_for(name)
        lines.append(f'struct Codex{name}: Codable, Sendable {{')
        for field in fields:
            prop = schema['properties'][field]
            optional = '' if field in schema.get('required', []) else '?'
            lines.append(f'    let {field}: {swift_type(prop)}{optional}')
        lines.extend(['}', ''])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--schema-dir', type=Path)
    parser.add_argument('--codex', default='codex')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] /
                        'Sources/SmthzCore/Chat/Codex/Generated/CodexProtocol.swift')
    args = parser.parse_args()
    if args.schema_dir:
        generate(args.schema_dir, args.output)
    else:
        with tempfile.TemporaryDirectory(prefix='smthz-codex-schema-') as temp:
            subprocess.run([args.codex, 'app-server', 'generate-json-schema', '--out', temp], check=True)
            generate(Path(temp), args.output)
